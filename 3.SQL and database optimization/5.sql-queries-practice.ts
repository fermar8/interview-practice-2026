import sqlite3 from 'sqlite3';

function openDatabase(path: string): Promise<sqlite3.Database> {
  return new Promise((resolve, reject) => {
    const db = new sqlite3.Database(path, (err) => {
      if (err) {
        reject(err);
        return;
      }
      resolve(db);
    });
  });
}

function closeDatabase(db: sqlite3.Database): Promise<void> {
  return new Promise((resolve, reject) => {
    db.close((err) => {
      if (err) {
        reject(err);
        return;
      }
      resolve();
    });
  });
}

function queryMany<T = unknown>(
  db: sqlite3.Database,
  sql: string,
  params: unknown[] = [],
): Promise<T[]> {
  return new Promise((resolve, reject) => {
    db.all(sql, params, (err, rows) => {
      if (err) {
        reject(err);
        return;
      }

      resolve(rows as T[]);
    });
  });
}

function queryOne<T = unknown>(
  db: sqlite3.Database,
  sql: string,
  params: unknown[] = [],
): Promise<T | undefined> {
  return new Promise((resolve, reject) => {
    db.get(sql, params, (err, row) => {
      if (err) {
        reject(err);
        return;
      }

      resolve(row as T | undefined);
    });
  });
}

// Find the top 5 customers who have spent the most money.
async function findTop5CustomersWhoSpentTheMost(db: sqlite3.Database): Promise<any[]> {
  const rows = await queryMany(
    db,
    `
    SELECT
        customers.CustomerId,
        customers.FirstName,
        customers.LastName,
        SUM(invoices.Total) AS TotalSpent
    FROM invoices
    JOIN customers
      ON invoices.CustomerId = customers.CustomerId
    GROUP BY
        customers.CustomerId,
        customers.FirstName,
        customers.LastName
    ORDER BY TotalSpent DESC
    LIMIT 5;
      `,
  );
  return rows;
}

// Return the last 10 invoices for a given CustomerId, 
// ordered by most recent first.
async function findLast10InvoicesForOneCustomerOrderByDate(db: sqlite3.Database): Promise<any> {
  const result = await queryMany(
    db,
    `
    SELECT
        customers.CustomerId,
        customers.FirstName,
        customers.LastName,
        invoices.InvoiceId,
        invoices.InvoiceDate,
        invoices.Total
    FROM invoices
    JOIN customers
      ON invoices.CustomerId = customers.CustomerId
    WHERE customers.CustomerId = ?
    ORDER BY invoices.InvoiceDate DESC
    LIMIT 10;
      `,
    [1], // Replace 1 with the desired CustomerId
  );
  return result;
}

// Find the total revenue generated by each artist, sorted highest to lowest.
async function findTotalRevenueByArtist(db: sqlite3.Database): Promise<any[]> {
  const result = await queryMany(
    db,
    `
    SELECT
      artists.ArtistId,
      artists.Name,
      SUM(invoice_items.UnitPrice * invoice_items.Quantity) AS TotalRevenue
    FROM artists
    JOIN albums
      ON artists.ArtistId = albums.ArtistId
    JOIN tracks
      ON albums.AlbumId = tracks.AlbumId
    JOIN invoice_items
      ON tracks.TrackId = invoice_items.TrackId
    GROUP BY artists.ArtistId, artists.Name
    ORDER BY TotalRevenue DESC;
      `,
  );
  return result;
}

// Find customers that never made a purchase.
async function findCustomersThatNeverMadeAPurchase(db: sqlite3.Database): Promise<any[]> {
  const result = await queryMany(
    // LEFT JOIN lets us keep all customers, even if they have no invoices
    db,
    `
    SELECT
      customers.CustomerId,
      customers.FirstName,
      customers.LastName
    FROM customers
    LEFT JOIN invoices
      ON customers.CustomerId = invoices.CustomerId
    WHERE invoices.InvoiceId IS NULL;
      `,
  );
  return result;
}

// PAGINATION: Get page 3 of invoices for a customer, 5 per page, newest first.

async function getInvoicesForCustomerWithPaginationOffSet(db: sqlite3.Database, customerId: number, page: number, pageSize: number): Promise<any[]> {
  const offset = (page - 1) * pageSize;
  const result = await queryMany(
    db,
    `
    SELECT
        customers.CustomerId,
        customers.FirstName,
        customers.LastName,
        invoices.InvoiceId,
        invoices.InvoiceDate,
        invoices.Total
    FROM invoices
    JOIN customers
      ON invoices.CustomerId = customers.CustomerId
    WHERE customers.CustomerId = ?
    ORDER BY invoices.InvoiceDate DESC
    LIMIT ? OFFSET ?;
      `,
    [customerId, pageSize, offset],
  );
  return result;
}

// If dataset is large, OFFSET can be inefficient. 
// In that case, we can use the last seen InvoiceDate as a cursor for pagination instead of OFFSET.

async function getInvoicesForCustomerWithPaginationCursorApproach(db: sqlite3.Database, customerId: number, lastInvoiceDate: string): Promise<any[]> {
  const result = await queryMany(
    db,
    `
    SELECT
        customers.CustomerId,
        customers.FirstName,
        customers.LastName,
        invoices.InvoiceId,
        invoices.InvoiceDate,
        invoices.Total
    FROM invoices
    JOIN customers
      ON invoices.CustomerId = customers.CustomerId
    WHERE customers.CustomerId = ?
      AND invoices.InvoiceDate > ?
    ORDER BY invoices.InvoiceDate DESC
    LIMIT 10;
      `,
    [customerId, lastInvoiceDate],
  );
  return result;
}


